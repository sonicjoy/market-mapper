SELECT
  JSON_VALUE(data, '$.event_ticker') AS event_ticker,
  ANY_VALUE(JSON_VALUE(data, '$.title')) AS title,
  ANY_VALUE(JSON_VALUE(data, '$.yes_sub_title')) AS yes_sub,
  STRING_AGG(DISTINCT JSON_VALUE(data, '$.ticker') LIMIT 6) AS tickers
FROM `rs-marketmaking.raw_ingestion_us.kalshi_raw`
WHERE insert_time > TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL 14 DAY)
  AND JSON_VALUE(data, '$.event_ticker') IN (
    'KXCLUBFGAME-26AUG11UNICOR',
    'KXCLUBFGAME-26AUG11PALJUV',
    'KXCLUBFGAME-26AUG11CDECAR',
    'KXCLUBFGAME-26AUG10SOCVIL',
    'KXCLUBFGAME-26AUG10VOLKAL',
    'KXCLUBFGAME-26AUG09CHDUDL',
    'KXCLUBFGAME-26AUG09FROLAZ',
    'KXCLUBFGAME-26AUG09MCIATM',
    'KXCLUBFGAME-26AUG09PARSAM',
    'KXCLUBFGAME-26AUG09OLOSAB',
    'KXCLUBFGAME-26AUG09LECSSM',
    'KXCLUBFGAME-26AUG09MOSTVA',
    'KXCLUBFGAME-26AUG09OLMATH',
    'KXCLUBFGAME-26AUG09PROIMP',
    'KXCLUBFGAME-26AUG09PAULEE',
    'KXUFCFIGHT-26AUG15WELORO',
    'KXUFCFIGHT-26AUG08JOHVAZ',
    'KXUFCFIGHT-26AUG08CANFOR'
  )
GROUP BY 1
ORDER BY 1